"""Generate the offline Flutter personality catalog from the server's source."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
items = json.loads((ROOT / 'backend/data/coach_personas.json').read_text(encoding='utf-8'))
fields = ['id', 'name', 'style', 'animal', 'color', 'greeting', 'tap_line', 'thinking_line',
          'reply_line', 'training_line', 'lead_line', 'meal_line']
def camel(key):
    parts = key.split('_')
    return parts[0] + ''.join(p.title() for p in parts[1:])

text = '// Generated by scripts/build_coach_personas.py; edit backend/data/coach_personas.json.\n'
text += "import 'package:flutter/material.dart';\n\nclass CoachPersona {\n  const CoachPersona({\n"
text += ''.join(f'    required this.{camel(k)},\n' for k in fields)
text += '  });\n  final String ' + ', '.join(camel(k) for k in fields) + ';\n'
text += "  Color get accent => Color(int.parse('ff$color', radix: 16));\n}\n\n"
text += 'const coachPersonas = <CoachPersona>[\n'
for item in items:
    text += '  CoachPersona(\n'
    text += ''.join(f'    {camel(k)}: {json.dumps(item[k], ensure_ascii=False)},\n' for k in fields)
    text += '  ),\n'
text += '];\n\nCoachPersona personaFor(String id) => coachPersonas.firstWhere((p) => p.id == id, orElse: () => coachPersonas.first);\n'
target = ROOT / 'mobile/lib/coaches/coach_persona.dart'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(text, encoding='utf-8')
print(target)
